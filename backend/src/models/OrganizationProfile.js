import { DataTypes, Model } from 'sequelize';
import { sequelize } from '../db/index.js';

export class OrganizationProfile extends Model {
  toSafeJSON() {
    return {
      id: this.id,
      organizationId: this.organizationId,
      legalName: this.legalName || '',
      tradeName: this.tradeName || '',
      document: this.document || '',
      stateRegistration: this.stateRegistration || '',
      municipalInscription: this.municipalInscription || '',
      email: this.email || '',
      phone: this.phone || '',
      addressStreet: this.addressStreet || '',
      addressNumber: this.addressNumber || '',
      addressComplement: this.addressComplement || '',
      addressNeighborhood: this.addressNeighborhood || '',
      addressCity: this.addressCity || '',
      addressState: this.addressState || '',
      addressZip: this.addressZip || '',
      addressCountry: this.addressCountry || 'Brasil',
      cnaePrimary: this.cnaePrimary || '',
      cnaeSecondary: Array.isArray(this.cnaeSecondary) ? this.cnaeSecondary : [],
      taxRegime: this.taxRegime,
      simplesAnexoDefault: this.simplesAnexoDefault || 'V',
      payroll12m: Number(this.payroll12m || 0),
      payroll12mUpdatedAt: this.payroll12mUpdatedAt || null,
      revenueAdjustments: Array.isArray(this.revenueAdjustments) ? this.revenueAdjustments : [],
      asaasEnv: this.asaasEnv || 'sandbox',
      asaasApiKeyConfigured: Boolean(this.asaasApiKey),
      asaasWalletId: this.asaasWalletId || '',
      webhookTokenConfigured: Boolean(this.webhookToken),
      nfMunicipalServiceId: this.nfMunicipalServiceId || '',
      nfMunicipalServiceCode: this.nfMunicipalServiceCode || '',
      nfMunicipalServiceName: this.nfMunicipalServiceName || '',
      nfTaxes: this.nfTaxes || null,
      nfDescriptionDefault: this.nfDescriptionDefault || 'Serviços de suporte técnico',
      defaultAccountId: this.defaultAccountId || null,
      defaultReceivableCategoryId: this.defaultReceivableCategoryId || null,
      defaultPayableCategoryId: this.defaultPayableCategoryId || null,
      defaultTaxCategoryId: this.defaultTaxCategoryId || null,
      defaultCostCenterId: this.defaultCostCenterId || null,
      createdAt: this.createdAt,
      updatedAt: this.updatedAt,
    };
  }
}

OrganizationProfile.init(
  {
    id: {
      type: DataTypes.UUID,
      defaultValue: DataTypes.UUIDV4,
      primaryKey: true,
    },
    organizationId: {
      type: DataTypes.UUID,
      allowNull: false,
      unique: true,
      field: 'organization_id',
    },
    legalName: { type: DataTypes.STRING(180), allowNull: true, field: 'legal_name' },
    tradeName: { type: DataTypes.STRING(180), allowNull: true, field: 'trade_name' },
    document: { type: DataTypes.STRING(20), allowNull: true },
    stateRegistration: { type: DataTypes.STRING(40), allowNull: true, field: 'state_registration' },
    municipalInscription: {
      type: DataTypes.STRING(40),
      allowNull: true,
      field: 'municipal_inscription',
    },
    email: { type: DataTypes.STRING(180), allowNull: true },
    phone: { type: DataTypes.STRING(40), allowNull: true },
    addressStreet: { type: DataTypes.STRING(190), allowNull: true, field: 'address_street' },
    addressNumber: { type: DataTypes.STRING(30), allowNull: true, field: 'address_number' },
    addressComplement: {
      type: DataTypes.STRING(120),
      allowNull: true,
      field: 'address_complement',
    },
    addressNeighborhood: {
      type: DataTypes.STRING(120),
      allowNull: true,
      field: 'address_neighborhood',
    },
    addressCity: { type: DataTypes.STRING(120), allowNull: true, field: 'address_city' },
    addressState: { type: DataTypes.STRING(80), allowNull: true, field: 'address_state' },
    addressZip: { type: DataTypes.STRING(20), allowNull: true, field: 'address_zip' },
    addressCountry: {
      type: DataTypes.STRING(80),
      allowNull: true,
      defaultValue: 'Brasil',
      field: 'address_country',
    },
    cnaePrimary: { type: DataTypes.STRING(20), allowNull: true, field: 'cnae_primary' },
    cnaeSecondary: { type: DataTypes.JSON, allowNull: true, field: 'cnae_secondary' },
    taxRegime: {
      type: DataTypes.ENUM('simples_nacional', 'lucro_presumido', 'lucro_real', 'mei'),
      allowNull: false,
      defaultValue: 'simples_nacional',
      field: 'tax_regime',
    },
    simplesAnexoDefault: {
      type: DataTypes.STRING(8),
      allowNull: false,
      defaultValue: 'V',
      field: 'simples_anexo_default',
    },
    payroll12m: {
      type: DataTypes.DECIMAL(15, 2),
      allowNull: false,
      defaultValue: 0,
      field: 'payroll_12m',
    },
    payroll12mUpdatedAt: {
      type: DataTypes.DATEONLY,
      allowNull: true,
      field: 'payroll_12m_updated_at',
    },
    revenueAdjustments: { type: DataTypes.JSON, allowNull: true, field: 'revenue_adjustments' },
    asaasEnv: {
      type: DataTypes.ENUM('sandbox', 'production'),
      allowNull: false,
      defaultValue: 'sandbox',
      field: 'asaas_env',
    },
    asaasApiKey: { type: DataTypes.TEXT, allowNull: true, field: 'asaas_api_key' },
    asaasWalletId: { type: DataTypes.STRING(80), allowNull: true, field: 'asaas_wallet_id' },
    webhookToken: { type: DataTypes.STRING(120), allowNull: true, field: 'webhook_token' },
    nfMunicipalServiceId: {
      type: DataTypes.STRING(80),
      allowNull: true,
      field: 'nf_municipal_service_id',
    },
    nfMunicipalServiceCode: {
      type: DataTypes.STRING(40),
      allowNull: true,
      field: 'nf_municipal_service_code',
    },
    nfMunicipalServiceName: {
      type: DataTypes.STRING(255),
      allowNull: true,
      field: 'nf_municipal_service_name',
    },
    nfTaxes: { type: DataTypes.JSON, allowNull: true, field: 'nf_taxes' },
    nfDescriptionDefault: {
      type: DataTypes.STRING(255),
      allowNull: true,
      field: 'nf_description_default',
    },
    defaultAccountId: { type: DataTypes.UUID, allowNull: true, field: 'default_account_id' },
    defaultReceivableCategoryId: {
      type: DataTypes.UUID,
      allowNull: true,
      field: 'default_receivable_category_id',
    },
    defaultPayableCategoryId: {
      type: DataTypes.UUID,
      allowNull: true,
      field: 'default_payable_category_id',
    },
    defaultTaxCategoryId: {
      type: DataTypes.UUID,
      allowNull: true,
      field: 'default_tax_category_id',
    },
    defaultCostCenterId: {
      type: DataTypes.UUID,
      allowNull: true,
      field: 'default_cost_center_id',
    },
  },
  {
    sequelize,
    modelName: 'OrganizationProfile',
    tableName: 'organization_profiles',
  },
);
